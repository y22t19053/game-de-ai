import fs from 'node:fs';

function patch(file, pairs) {
  let s = fs.readFileSync(file, 'utf8');
  for (const [a, b] of pairs) {
    if (!s.includes(a)) {
      console.error('MISS in', file, ':', a.slice(0, 60));
      process.exit(1);
    }
    s = s.replace(a, b);
  }
  fs.writeFileSync(file, s, 'utf8');
  console.log('patched', file);
}

